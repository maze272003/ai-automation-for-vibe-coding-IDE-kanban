// apps/orchestrator/src/github/pr-evidence.ts
import { acceptanceCriteria, reviewAcResults, reviewFindings, reviews, userStories, verificationChecks, verificationRuns, type AikDb } from '@aik/db';
import { and, desc, eq } from 'drizzle-orm';
import { git } from '../git/git.ts';

export interface CriterionEvidence {
  ordinal: number;
  text: string;
  status: 'met' | 'unmet' | 'unclear';
  evidence?: string;
}

export interface VerificationCheckEvidence {
  key: string;
  status: string;
  durationMs?: number;
  commitSha: string;
}

export interface ReviewFindingEvidence {
  key: string;
  severity: string;
  explanation: string;
}

export interface ReviewEvidence {
  verdict: string;
  actor: string;
  summary: string;
  blockingFindingsCount: number;
  findings: ReviewFindingEvidence[];
}

export interface CommitEvidence {
  sha: string;
  message: string;
}

export interface PullRequestBodyData {
  story: {
    key: string;
    title: string;
    description: string;
    attemptCount: number;
    candidateSha: string;
  };
  acceptanceCriteria: CriterionEvidence[];
  verificationChecks: VerificationCheckEvidence[];
  review: ReviewEvidence | null;
  commits: CommitEvidence[];
}

export function formatPullRequestBody(data: PullRequestBodyData): string {
  const lines: string[] = [];

  // Story header
  lines.push(`## Story: ${data.story.key} — ${data.story.title}`);
  lines.push('');
  if (data.story.description.trim()) {
    lines.push(data.story.description.trim());
    lines.push('');
  }

  lines.push('---');
  lines.push('');

  // Acceptance Criteria Checklist
  lines.push('### Acceptance Criteria');
  lines.push('');
  if (data.acceptanceCriteria.length === 0) {
    lines.push('*No acceptance criteria specified.*');
  } else {
    for (const ac of data.acceptanceCriteria) {
      const box = ac.status === 'met' ? '[x]' : '[ ]';
      const statusLabel = ac.status.toUpperCase();
      lines.push(`- ${box} **AC-${ac.ordinal}** (${statusLabel}): ${ac.text}`);
      if (ac.evidence && ac.evidence.trim()) {
        lines.push(`  > ${ac.evidence.trim().replace(/\n/g, '\n  > ')}`);
      }
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  // Verification Evidence Table
  lines.push('### Verification Evidence');
  lines.push('');
  if (data.verificationChecks.length === 0) {
    lines.push('*No verification checks recorded.*');
  } else {
    lines.push('| Check | Status | Duration | Commit SHA |');
    lines.push('| :--- | :--- | :--- | :--- |');
    for (const vc of data.verificationChecks) {
      const duration = vc.durationMs !== undefined ? `${(vc.durationMs / 1000).toFixed(1)}s` : '-';
      const shortSha = vc.commitSha.slice(0, 7);
      lines.push(`| \`${vc.key}\` | **${vc.status}** | ${duration} | \`${shortSha}\` |`);
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  // Review Summary
  lines.push('### AI Review');
  lines.push('');
  if (!data.review) {
    lines.push('*No review recorded.*');
  } else {
    lines.push(`**Verdict:** \`${data.review.verdict}\` (Actor: ${data.review.actor})`);
    lines.push('');
    lines.push(`> ${data.review.summary.trim().replace(/\n/g, '\n> ')}`);
    lines.push('');
    if (data.review.findings.length > 0) {
      lines.push(`#### Findings (${data.review.blockingFindingsCount} blocking):`);
      for (const f of data.review.findings) {
        lines.push(`- **${f.key}** [${f.severity.toUpperCase()}]: ${f.explanation}`);
      }
    } else {
      lines.push('*No findings recorded.*');
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  // Commits
  lines.push('### Commits');
  lines.push('');
  if (data.commits.length === 0) {
    lines.push('*No commits found.*');
  } else {
    for (const c of data.commits) {
      lines.push(`- \`${c.sha.slice(0, 7)}\` ${c.message}`);
    }
  }
  lines.push('');
  lines.push('---');
  lines.push(`*Generated by AI Kanban (Attempt ${data.story.attemptCount})*`);

  return lines.join('\n');
}

export async function gatherPullRequestBodyData(
  db: AikDb,
  storyId: number,
  repoPath: string,
  baseRef: string,
): Promise<PullRequestBodyData> {
  const story = db.select().from(userStories).where(eq(userStories.id, storyId)).get();
  if (!story || !story.candidateSha) {
    throw new Error(`Story ${storyId} not found or has no candidateSha`);
  }

  // 1. Acceptance Criteria & results
  const acRows = db
    .select()
    .from(acceptanceCriteria)
    .where(and(eq(acceptanceCriteria.storyId, storyId), eq(acceptanceCriteria.storyRevision, story.revision)))
    .orderBy(acceptanceCriteria.ordinal)
    .all();

  // Find latest review for candidate
  const latestReview = db
    .select()
    .from(reviews)
    .where(and(eq(reviews.storyId, storyId), eq(reviews.commitSha, story.candidateSha)))
    .orderBy(desc(reviews.id))
    .get();

  const acResults = latestReview
    ? db.select().from(reviewAcResults).where(eq(reviewAcResults.reviewId, latestReview.id)).all()
    : [];

  const acResultMap = new Map<number, { status: 'met' | 'unmet' | 'unclear'; evidence: string }>();
  for (const r of acResults) {
    acResultMap.set(r.acceptanceCriterionId, { status: r.status as 'met' | 'unmet' | 'unclear', evidence: r.evidence });
  }

  const criteriaEvidence: CriterionEvidence[] = acRows.map((ac) => {
    const res = acResultMap.get(ac.id);
    return {
      ordinal: ac.ordinal,
      text: ac.text,
      status: res ? res.status : 'unclear',
      evidence: res ? res.evidence : undefined,
    };
  });

  // 2. Verification checks from latest run for candidate
  const latestRun = db
    .select()
    .from(verificationRuns)
    .where(and(eq(verificationRuns.storyId, storyId), eq(verificationRuns.commitSha, story.candidateSha)))
    .orderBy(desc(verificationRuns.id))
    .get();

  const checkRows = latestRun
    ? db.select().from(verificationChecks).where(eq(verificationChecks.verificationRunId, latestRun.id)).all()
    : [];

  const verificationEvidence: VerificationCheckEvidence[] = checkRows.map((vc) => ({
    key: vc.checkKey,
    status: vc.status,
    durationMs: vc.endedAt && vc.startedAt ? vc.endedAt.getTime() - vc.startedAt.getTime() : undefined,
    commitSha: story.candidateSha!,
  }));

  // 3. Review evidence
  let reviewEvidence: ReviewEvidence | null = null;
  if (latestReview) {
    const findingsRows = db
      .select()
      .from(reviewFindings)
      .where(eq(reviewFindings.reviewId, latestReview.id))
      .all();

    reviewEvidence = {
      verdict: latestReview.verdict,
      actor: latestReview.actor,
      summary: latestReview.summary,
      blockingFindingsCount: findingsRows.filter((f) => f.blocking).length,
      findings: findingsRows.map((f) => ({
        key: f.findingKey,
        severity: f.severity,
        explanation: f.explanation,
      })),
    };
  }

  // 4. Commits between base and candidate
  const commits: CommitEvidence[] = [];
  try {
    const logOutput = await git(
      ['log', '--oneline', '--no-decorate', `${baseRef}..${story.candidateSha}`],
      { cwd: repoPath },
    );
    if (logOutput.trim()) {
      for (const line of logOutput.split(/\r?\n/)) {
        const spaceIdx = line.indexOf(' ');
        if (spaceIdx > 0) {
          commits.push({
            sha: line.slice(0, spaceIdx),
            message: line.slice(spaceIdx + 1),
          });
        }
      }
    }
  } catch {
    // Fallback if baseRef..candidate not traversable
    commits.push({
      sha: story.candidateSha,
      message: `Candidate ${story.candidateSha.slice(0, 7)}`,
    });
  }

  return {
    story: {
      key: story.key,
      title: story.title,
      description: story.description,
      attemptCount: story.attemptCount,
      candidateSha: story.candidateSha,
    },
    acceptanceCriteria: criteriaEvidence,
    verificationChecks: verificationEvidence,
    review: reviewEvidence,
    commits,
  };
}

// apps/orchestrator/test/pr-evidence.test.ts
import {
  acceptanceCriteria,
  projects,
  reviewAcResults,
  reviews,
  userStories,
  verificationChecks,
  verificationRuns,
} from '@aik/db';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import {
  formatPullRequestBody,
  gatherPullRequestBodyData,
  type PullRequestBodyData,
} from '../src/github/pr-evidence.ts';
import { createTestDb } from './helpers/db.ts';
import { makeTempRepo } from './helpers/temp.ts';

describe('PR Body Evidence Generator (§14)', () => {
  it('formats PR body from evidence data correctly', () => {
    const data: PullRequestBodyData = {
      story: {
        key: 'INV-42',
        title: 'Add User Authentication',
        description: 'Implements login and logout flow.',
        attemptCount: 2,
        candidateSha: 'a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2',
      },
      acceptanceCriteria: [
        { ordinal: 1, text: 'User can log in', status: 'met', evidence: 'Verified with login.test.ts' },
        { ordinal: 2, text: 'User can log out', status: 'unmet' },
      ],
      verificationChecks: [
        { key: 'lint', status: 'passed', durationMs: 1200, commitSha: 'a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2' },
        { key: 'test', status: 'passed', durationMs: 3400, commitSha: 'a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2' },
      ],
      review: {
        verdict: 'APPROVED',
        actor: 'agent',
        summary: 'All checks passed and criteria verified.',
        blockingFindingsCount: 0,
        findings: [
          { key: 'F-1', severity: 'low', explanation: 'Consider adding more tests.' },
        ],
      },
      commits: [
        { sha: 'a1b2c3d', message: 'feat: add login' },
        { sha: 'e5f6a1b', message: 'test: add auth tests' },
      ],
    };

    const body = formatPullRequestBody(data);

    expect(body).toContain('## Story: INV-42 — Add User Authentication');
    expect(body).toContain('Implements login and logout flow.');
    expect(body).toContain('- [x] **AC-1** (MET): User can log in');
    expect(body).toContain('> Verified with login.test.ts');
    expect(body).toContain('- [ ] **AC-2** (UNMET): User can log out');
    expect(body).toContain('| `lint` | **passed** | 1.2s | `a1b2c3d` |');
    expect(body).toContain('| `test` | **passed** | 3.4s | `a1b2c3d` |');
    expect(body).toContain('**Verdict:** `APPROVED` (Actor: agent)');
    expect(body).toContain('> All checks passed and criteria verified.');
    expect(body).toContain('- **F-1** [LOW]: Consider adding more tests.');
    expect(body).toContain('- `a1b2c3d` feat: add login');
    expect(body).toContain('*Generated by AI Kanban (Attempt 2)*');
  });

  describe('gatherPullRequestBodyData', () => {
    let dbHolder: ReturnType<typeof createTestDb>;
    let tempRepoPath: string;
    let storyId: number;
    let candidateSha: string;
    const baseRef = 'HEAD~1';

    beforeAll(() => {
      dbHolder = createTestDb();
      tempRepoPath = makeTempRepo();

      // Create a commit for candidate
      fs.writeFileSync(path.join(tempRepoPath, 'feature.txt'), 'feature code');
      execFileSync('git', ['add', '.'], { cwd: tempRepoPath });
      execFileSync('git', ['-c', 'user.name=test', '-c', 'user.email=test@test.com', 'commit', '-m', 'feat: feature commit'], { cwd: tempRepoPath });
      candidateSha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: tempRepoPath, encoding: 'utf8' }).trim();

      const now = new Date();

      const project = dbHolder.db
        .insert(projects)
        .values({
          name: 'Test Project',
          key: 'TEST',
          repoPath: tempRepoPath,
          baseBranch: 'main',
          settings: {
            checks: [],
            shellAllowlist: [],
            protectedPaths: [],
            secretsOnlyVerification: false,
            publish: true,
            remoteMerge: false,
            requireRemoteChecks: true,
            autoAcceptPlans: false,
            maxAttempts: 3,
            allowPaid: false,
            allowMayTrain: false,
            webfetch: false,
            mergeMethod: 'merge',
            budgets: { requestsPerRun: 10, requestsPerStory: 20, inputTokensPerStory: 1000 },
            jobLimits: { memoryMb: 512, maxProcesses: 10 },
          },
          createdAt: now,
          updatedAt: now,
        })
        .returning()
        .get();

      const story = dbHolder.db
        .insert(userStories)
        .values({
          projectId: project.id,
          key: 'TEST-1',
          title: 'First Story',
          description: 'Story details here',
          priority: 'P1',
          rank: 1,
          revision: 1,
          status: 'AWAITING_MERGE',
          statusVersion: 1,
          attemptCount: 1,
          candidateSha,
          createdAt: now,
          updatedAt: now,
        })
        .returning()
        .get();
      storyId = story.id;

      // Acceptance criteria
      const ac1 = dbHolder.db
        .insert(acceptanceCriteria)
        .values({
          storyId,
          storyRevision: 1,
          ordinal: 1,
          text: 'Criteria one',
          source: 'human',
          createdAt: now,
        })
        .returning()
        .get();

      // Verification Run & Check
      const vRun = dbHolder.db
        .insert(verificationRuns)
        .values({
          storyId,
          commitSha: candidateSha,
          trigger: 'candidate',
          status: 'passed',
          startedAt: new Date(now.getTime() - 2000),
          endedAt: now,
        })
        .returning()
        .get();

      dbHolder.db
        .insert(verificationChecks)
        .values({
          verificationRunId: vRun.id,
          checkKey: 'test',
          mandatory: true,
          command: 'npm test',
          cwd: tempRepoPath,
          status: 'passed',
          exitCode: 0,
          startedAt: new Date(now.getTime() - 2000),
          endedAt: now,
        })
        .run();

      // Review
      const rev = dbHolder.db
        .insert(reviews)
        .values({
          storyId,
          commitSha: candidateSha,
          actor: 'agent',
          rawVerdict: 'APPROVED',
          verdict: 'APPROVED',
          summary: 'Looks good',
          raw: { schemaVersion: 1, verdict: 'APPROVED', summary: 'Looks good', acChecklist: [], findings: [], priorFindings: [] },
          createdAt: now,
        })
        .returning()
        .get();

      dbHolder.db
        .insert(reviewAcResults)
        .values({
          reviewId: rev.id,
          acceptanceCriterionId: ac1.id,
          status: 'met',
          evidence: 'Code matches requirement',
        })
        .run();
    });

    it('gathers all evidence from database and git history', async () => {
      const data = await gatherPullRequestBodyData(dbHolder.db, storyId, tempRepoPath, baseRef);

      expect(data.story.key).toBe('TEST-1');
      expect(data.story.candidateSha).toBe(candidateSha);
      expect(data.acceptanceCriteria).toHaveLength(1);
      expect(data.acceptanceCriteria[0]!.status).toBe('met');
      expect(data.acceptanceCriteria[0]!.evidence).toBe('Code matches requirement');
      expect(data.verificationChecks).toHaveLength(1);
      expect(data.verificationChecks[0]!.key).toBe('test');
      expect(data.verificationChecks[0]!.status).toBe('passed');
      expect(data.review?.verdict).toBe('APPROVED');
      expect(data.commits.length).toBeGreaterThanOrEqual(1);

      const formatted = formatPullRequestBody(data);
      expect(formatted).toContain('## Story: TEST-1 — First Story');
      expect(formatted).toContain('- [x] **AC-1** (MET): Criteria one');
      expect(formatted).toContain('> Code matches requirement');
      expect(formatted).toContain('| `test` | **passed** |');
      expect(formatted).toContain('**Verdict:** `APPROVED`');
    });
  });
});

export const PIXEL_FONT: Record<string, string[]> = Object.fromEntries(
  Object.entries(RAW).map(([ch, rows]) => [ch, rows.split('|')]),
);

const glyphFor = (ch: string): string[] => PIXEL_FONT[ch] ?? PIXEL_FONT['?']!;

/** Width in px of `text` at integer `scale` (5 px per glyph + 1 px spacing between glyphs). */
export function measurePixelText(text: string, scale: number): number {
  const n = [...text].length;
  return n === 0 ? 0 : (n * GLYPH_W + (n - 1) * SPACING) * scale;
}

/** Draws text with fillRect only (crisp pixels, deterministic). Unknown glyphs draw as '?'. */
export function paintPixelText(ctx: Ctx2D, text: string, x: number, y: number, scale: number, color: string): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const rows = glyphFor(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r]!;
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '#') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + SPACING) * scale;
  }
}
